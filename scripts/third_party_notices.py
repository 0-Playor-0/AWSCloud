"""Write THIRD_PARTY_NOTICES.md from what ships: the frontend's production dependency tree
(a conservative superset of the bundle, plus the self-hosted OCR model and fonts) and the Python
packages in the Lambda build. Run after `npm ci` (frontend/) and `sam build`.

    .venv/bin/python scripts/third_party_notices.py
"""

from __future__ import annotations

import email
import json
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FRONTEND = ROOT / "frontend"
LAMBDA_BUILD = ROOT / ".aws-sam" / "build" / "ApiFunction"
LICENSE_NAMES = ("LICENSE", "LICENCE", "COPYING", "NOTICE", "OFL")
SKIP = {"encoding", "remix"}  # optional peers that are not installed
# Dev dependencies whose files are copied into the site at build time (scripts/copy-ocr-assets.mjs).
SHIPPED_DEV = {"@tesseract.js-data/eng"}


def _license_texts(folder: Path) -> list[str]:
    texts = []
    for f in sorted(folder.rglob("*")):
        if (f.is_file() and f.name.upper().startswith(LICENSE_NAMES)
                and "node_modules" not in f.relative_to(folder).parts):
            texts.append(f.read_text(errors="replace").strip())
    return texts


def npm_packages() -> list[tuple[str, str, str, list[str]]]:
    out = subprocess.run(["npm", "ls", "--omit=dev", "--all", "--parseable"], cwd=FRONTEND,
                         capture_output=True, text=True, check=False).stdout
    folders = [Path(line) for line in out.splitlines() if line and Path(line) != FRONTEND]
    folders += [FRONTEND / "node_modules" / name for name in SHIPPED_DEV]

    seen: dict[tuple[str, str], Path] = {}
    for folder in folders:
        meta = json.loads((folder / "package.json").read_text())
        seen[(meta["name"], meta["version"])] = folder

    rows = []
    for (name, version), folder in sorted(seen.items()):
        if name in SKIP or name.startswith("@types/"):
            continue
        meta = json.loads((folder / "package.json").read_text())
        lic = meta.get("license") or meta.get("licenses") or "see text"
        rows.append((name, version, str(lic), _license_texts(folder)))
    return rows


def python_packages() -> list[tuple[str, str, str, list[str]]]:
    rows = []
    for info in sorted(LAMBDA_BUILD.glob("*.dist-info")):
        meta = email.message_from_string((info / "METADATA").read_text())
        lic = meta.get("License-Expression") or meta.get("License") or "see text"
        if len(lic) > 60:  # some packages put the whole text in this field
            lic = "see text"
        rows.append((meta["Name"], meta["Version"], lic, _license_texts(info)))
    return rows


def main() -> None:
    npm, py = npm_packages(), python_packages()
    lines = [
        "# Third-party notices",
        "",
        "Namma Check is MIT licensed (see LICENSE). It ships or depends on the software and assets",
        "below. The website list is the full production dependency tree of `frontend/`, a superset",
        "of what the bundler keeps. It includes the self-hosted OCR engine (Tesseract.js and",
        "tesseract.js-core), the English OCR model (`@tesseract.js-data/eng`, from Tesseract's",
        "tessdata) and the fonts (Anton, Playfair Display, IBM Plex Sans and IBM Plex Mono via",
        "Fontsource, under the SIL Open Font License 1.1). The Lambda list is the Python",
        "packages in the deployed function. Generated by `scripts/third_party_notices.py`;",
        "do not edit by hand.",
        "",
        "## Bundled assets",
        "",
        "| Asset | Source | License |",
        "|---|---|---|",
        "| `ocr/<versions>/lang/eng.traineddata.gz` (English OCR model, 4.0.0 best_int) |"
        " Tesseract OCR tessdata_best (https://github.com/tesseract-ocr/tessdata_best), packaged"
        " by `@tesseract.js-data/eng` | Apache-2.0 (model data); packaging MIT |",
        "| `ocr/<versions>/worker.min.js`, `core/*.wasm.js` | Tesseract.js, tesseract.js-core"
        " (Tesseract OCR compiled to WebAssembly) | Apache-2.0 |",
        "| Fonts (`assets/*.woff2`) | Anton; Playfair Display; IBM Plex Sans; IBM Plex Mono (via"
        " Fontsource) | SIL Open Font License 1.1 |",
        "| Illustrations (`assets/*.webp`, newspaper border; sources in"
        " `frontend/src/assets/images/`) | Illustrations: [SOURCE PENDING — ask Hiral] |"
        " [SOURCE PENDING — ask Hiral] |",
        "",
        "## Website (browser)",
        "",
        "| Package | Version | License |",
        "|---|---|---|",
        *[f"| {n} | {v} | {lic} |" for n, v, lic, _ in npm],
        "",
        "## API (AWS Lambda, Python)",
        "",
        "| Package | Version | License |",
        "|---|---|---|",
        *[f"| {n} | {v} | {lic} |" for n, v, lic, _ in py],
        "",
        "## License texts",
        "",
        "Identical texts are listed once with every package that ships them.",
        "",
    ]
    by_text: dict[str, list[str]] = {}
    for name, version, lic, texts in npm + py:
        for text in texts or [f"(No license file in the package; declared license: {lic}.)"]:
            by_text.setdefault(text, []).append(f"{name} {version}")
    for text, owners in by_text.items():
        lines += [f"### {', '.join(owners)}", "", "```", text, "```", ""]
    (ROOT / "THIRD_PARTY_NOTICES.md").write_text("\n".join(lines))
    print(f"{len(npm)} npm + {len(py)} python packages, {len(by_text)} distinct texts")


if __name__ == "__main__":
    main()
